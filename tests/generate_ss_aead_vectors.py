"""Public deterministic SIP004/SIP007 vectors, generated independently with Python cryptography."""
from pathlib import Path
import hashlib
import json
from cryptography.hazmat.primitives.ciphers.aead import AESGCM, ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives import hashes

PASSWORD = "pässword-测试".encode("utf-8")
METHODS = ("aes-128-gcm", "aes-256-gcm", "chacha20-ietf-poly1305")

def master_key(size):
    output = previous = b""
    while len(output) < size:
        previous = hashlib.md5(previous + PASSWORD).digest()
        output += previous
    return output[:size]

def subkey(master, salt):
    return HKDF(algorithm=hashes.SHA1(), length=len(master), salt=salt, info=b"ss-subkey").derive(master)

def frames(aead, chunks):
    wire, nonce = b"", 0
    for chunk in chunks:
        wire += aead.encrypt(nonce.to_bytes(12, "little"), len(chunk).to_bytes(2, "big"), None)
        nonce += 1
        wire += aead.encrypt(nonce.to_bytes(12, "little"), chunk, None)
        nonce += 1
    return wire

def generate():
    records = []
    for name in METHODS:
        size = 16 if name == "aes-128-gcm" else 32
        algorithm = ChaCha20Poly1305 if name.startswith("chacha") else AESGCM
        master, salt, remote_salt = master_key(size), bytes(range(size)), bytes(range(128, 128 + size))
        key, remote_key = subkey(master, salt), subkey(master, remote_salt)
        udp_plain = b"\x03\x0ewww.google.com\x01\xbbUDP fixture"
        empty_udp = b"\x03\x01x\x00\x35"
        record = [name, master.hex(), salt.hex(), key.hex(), remote_key.hex(),
            frames(algorithm(key), [b"hello world", b"next frame"]).hex(),
            (remote_salt + frames(algorithm(remote_key), [b"HTTP/1.1 204 No Content\r\n\r\n", b"server data"])).hex(),
            udp_plain.hex(), (salt + algorithm(key).encrypt(bytes(12), udp_plain, None)).hex(),
            empty_udp.hex(), (salt + algorithm(key).encrypt(bytes(12), empty_udp, None)).hex(),
            algorithm(key).encrypt(bytes(12), b"\xc0\x01", None).hex(),
        ]
        records.append("    {" + ",".join(json.dumps(value) for value in record) + "},\n")
    header = "// Generated by generate_ss_aead_vectors.py using Python cryptography, not production code.\n"
    header += "struct SsAeadVector { const char *method,*master,*salt,*key,*remoteKey,*client,*server,*udpPlain,*udpPacket,*emptyPlain,*emptyPacket,*reservedLength; };\n"
    header += "static const SsAeadVector SS_AEAD_VECTORS[] = {\n" + "".join(records) + "};\n"
    destination = Path(__file__).with_name("ss_aead_vectors.h")
    destination.write_text(header)
    print(f"Generated {len(records)} independent cipher vectors")

if __name__ == "__main__":
    generate()
